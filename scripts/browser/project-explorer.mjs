import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { origin, outputPath, httpCredentials } from './config.mjs';
import { installAssessment } from './assessment-fixtures.mjs';
import { testModules } from '../test-modules.mjs';

const modules = testModules(), { destinationHref } = modules.load('lib/navigation/model');
const browser = await chromium.launch(), label = process.argv[2] ?? 'candidate';
const out = { label, checks: [], errors: [] }, cleanups = [];
const current = page => JSON.parse(new URL(page.url()).searchParams.get('destination'));
try {
  for (const owner of ['am', 'kf']) {
    const context = await browser.newContext({ httpCredentials, colorScheme: owner === 'am' ? 'dark' : 'light', reducedMotion: 'reduce', viewport: { width: 1440, height: 1000 } });
    const fixture = await installAssessment(context, { profileId: owner }); cleanups.push(fixture.cleanup);
    const page = await context.newPage(); page.on('pageerror', error => out.errors.push(error.message));
    const target = { projectId: 'trailblazer-crm', worktreeId: owner === 'am' ? 'lead-routing' : null, orgId: 'uat' };
    await page.goto(origin + destinationHref({ version: 1, owner, surface: 'build', target }));
    const panel = page.locator('#workspace-panel');
    await page.getByRole('heading', { name: 'Keep your ideas moving.', exact: true }).waitFor();
    if (await panel.getAttribute('data-open') !== 'true') await page.locator('#workspace-panel-toggle').click();
    const projects = panel.getByRole('region', { name: 'Projects', exact: true });
    const row = projects.getByRole('button').filter({ has: page.getByText(owner === 'am' ? 'lead-routing' : 'Trailblazer CRM', { exact: true }) });
    assert.equal(await panel.getByRole('button', { name: /Explore files/ }).count(), 0);
    await row.focus(); await row.press('ArrowRight');
    const explorer = panel.getByRole('region', { name: 'Project explorer', exact: true });
    const search = explorer.getByRole('textbox', { name: 'Find project files', exact: true });
    await explorer.getByRole('heading', { name: 'Trailblazer CRM', exact: true }).waitFor();
    assert.equal(await explorer.getByText('feature/lead-routing', { exact: true }).count(), owner === 'am' ? 1 : 0);
    const folders = explorer.locator('summary');
    await folders.filter({ hasText: /^permissionsets$/ }).click();
    const permission = 'force-app/main/default/permissionsets/Lead_Routing_User.permissionset-meta.xml';
    const file = explorer.getByRole('button', { name: `Open file ${permission}`, exact: true });
    await file.focus(); await file.press('Enter');
    await page.getByRole('article', { name: 'Lead_Routing_User.permissionset-meta.xml file', exact: true }).waitFor();
    assert.equal(await file.getAttribute('aria-current'), 'page');
    assert.deepEqual(current(page).target, target);
    assert.equal(current(page).surface, 'build');
    await search.fill('W-9821'); assert.equal(await explorer.getByRole('button', { name: /^Open file / }).count(), 0);
    await search.fill('Storefront'); assert.equal(await explorer.getByRole('button', { name: /^Open file / }).count(), 0);
    await search.fill('README');
    await explorer.getByRole('button', { name: 'Open file README.md', exact: true }).click();
    await page.getByRole('article', { name: 'README.md file', exact: true }).waitFor();
    assert.equal(current(page).surface, 'alm'); assert.deepEqual(current(page).target, target);
    if (owner === 'am') {
      await search.fill('OpportunityTriggerHandler');
      await explorer.getByRole('button', { name: /Open file .*OpportunityTriggerHandler.cls$/, exact: true }).click();
      await page.getByRole('article', { name: 'OpportunityTriggerHandler.cls file', exact: true }).waitFor();
      assert.equal(current(page).surface, 'code'); assert.deepEqual(current(page).target, target);
    }
    await explorer.getByRole('button', { name: 'Clear file search', exact: true }).click();
    assert.equal(await search.inputValue(), ''); assert(await search.evaluate(el => document.activeElement === el));
    await page.screenshot({ path: outputPath(`${label}-explorer-${owner}.png`) });
    const before = page.url();
    await explorer.getByRole('button', { name: 'All projects', exact: true }).click();
    await page.waitForFunction(() => document.activeElement?.getAttribute('aria-keyshortcuts') === 'ArrowRight');
    assert(await row.evaluate(el => el === document.activeElement), 'All projects restores focus to the selected project/worktree');
    assert.equal(page.url(), before);
    await row.dblclick();
    await page.reload();
    await page.getByRole('article', { name: owner === 'am' ? 'OpportunityTriggerHandler.cls file' : 'README.md file', exact: true }).waitFor();
    assert.deepEqual(current(page).target, target);
    await row.dblclick();
    await page.getByRole('link', { name: 'Global home', exact: true }).click();
    await page.getByRole('group', { name: 'Today', exact: true }).waitFor();
    assert.equal(await panel.getByRole('region', { name: 'Project explorer', exact: true }).count(), 0);
    assert.equal(await panel.getByRole('button', { name: /^Explore files in / }).count(), 0);
    await projects.getByRole('button').filter({ has: page.getByText('Customer Onboarding', { exact: true }) }).dblclick();
    await search.fill('Customer_Welcome');
    await explorer.getByRole('button', { name: /Open file .*Customer_Welcome.flow-meta.xml$/ }).click();
    await page.getByRole('article', { name: 'Customer_Welcome.flow-meta.xml file', exact: true }).waitFor();
    assert.equal(current(page).target.projectId, 'customer-onboarding');
    assert.equal(await page.getByRole('tab', { name: 'README.md', exact: true }).count(), 0, 'File tabs do not leak across projects');
    assert.equal(fixture.stats.commands.filter(command => command.kind.startsWith('canvas.') && command.canvas?.kind === 'project-file').length, 0, 'Browsing files does not save file drafts');
    assert(fixture.commands.every(command => command.kind === 'visit'), 'Browsing files does not invoke model work');
    if (owner === 'am') {
      await panel.getByRole('region', { name: 'Sessions', exact: true }).getByRole('button').filter({ hasText: 'hotfix-9821' }).click();
      await projects.waitFor();
      assert.equal(await explorer.count(), 0, 'An explicit worktree switch returns to the project list');
      await projects.getByRole('button').filter({ hasText: 'hotfix-9821' }).dblclick();
      await search.fill('W-9821');
      await explorer.getByRole('button', { name: /Open file .*W-9821-regression-tests.md$/ }).click();
      await page.getByRole('article', { name: 'W-9821-regression-tests.md file', exact: true }).waitFor();
      assert.equal(current(page).target.worktreeId, 'hotfix-9821');
      await search.fill('lead-routing-agent');
      assert.equal(await explorer.getByRole('button', { name: /^Open file / }).count(), 0, 'Sibling changes remain outside this worktree');
    }
    if (owner === 'kf') {
      await page.setViewportSize({ width: 390, height: 844 });
      if (await panel.getAttribute('data-open') !== 'true') await page.locator('#workspace-panel-toggle').click();
      await explorer.getByRole('button', { name: 'Clear file search', exact: true }).click();
      await page.screenshot({ path: outputPath(`${label}-explorer-narrow.png`) });
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Explorer does not overflow the viewport');
      await explorer.getByRole('button', { name: 'All projects', exact: true }).click();
      await projects.getByRole('button').filter({ has: page.getByText('Customer Onboarding', { exact: true }) }).waitFor();
    }
    out.checks.push(`${owner}: scoped folders, keyboard file opening, search/clear, applicable surfaces, return focus, reload, Home/project isolation and no write/model calls`);
    await context.close();
  }

  const context = await browser.newContext({ httpCredentials, colorScheme: 'dark', viewport: { width: 1440, height: 1000 } });
  const fixture = await installAssessment(context, { profileId: 'sp' }); cleanups.push(fixture.cleanup);
  const page = await context.newPage(); page.on('pageerror', error => out.errors.push(error.message));
  await page.goto(origin + destinationHref({ version: 1, owner: 'sp', surface: null, target: { projectId: null, worktreeId: null, orgId: 'uat' } }));
  const panel = page.locator('#workspace-panel');
  await page.getByRole('group', { name: 'Today', exact: true }).waitFor();
  if (await panel.getAttribute('data-open') !== 'true') await page.locator('#workspace-panel-toggle').click();
  await panel.getByRole('button', { name: 'Start project', exact: true }).click();
  await page.getByLabel('Project name', { exact: true }).fill('Service app');
  await page.getByRole('radio', { name: /^React app/ }).check();
  await page.getByLabel('What should this project achieve?', { exact: true }).fill('Reduce handoffs');
  await page.getByLabel('Context for the agent (optional)', { exact: true }).fill('Use existing sign-in');
  await page.getByLabel('Repository URL (optional)', { exact: true }).fill('https://github.com/acme/service');
  await page.getByRole('button', { name: 'Create project', exact: true }).click();
  await page.getByRole('heading', { name: 'Service app', exact: true }).waitFor();
  const project = fixture.state.snapshot.assessment.projects[0];
  const target = { projectId: project.id, worktreeId: null, orgId: 'uat' };
  await page.getByRole('link', { name: 'Global home', exact: true }).click();
  await page.getByRole('group', { name: 'Today', exact: true }).waitFor();
  await panel.getByRole('region', { name: 'Projects', exact: true }).getByRole('button').filter({ has: page.getByText('Service app', { exact: true }) }).dblclick();
  await panel.getByRole('button', { name: 'Open file .project/project.json', exact: true }).click();
  const contents = page.getByLabel('File contents', { exact: true });
  await page.getByRole('article', { name: 'project.json file', exact: true }).waitFor();
  const definition = JSON.parse(await contents.textContent());
  assert.equal(definition.goal, 'Reduce handoffs'); assert.equal(definition.context, 'Use existing sign-in');
  assert.equal(definition.projectType, 'react'); assert.equal(definition.repository, 'https://github.com/acme/service');
  assert.deepEqual(current(page).target, target);
  const downloading = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download file', exact: true }).click();
  const download = await downloading;
  assert.equal(download.suggestedFilename(), 'project.json');
  assert.deepEqual(JSON.parse(readFileSync(await download.path(), 'utf8')), definition);
  await panel.getByRole('button', { name: 'Open file .project/work-items.json', exact: true }).click();
  await page.getByRole('article', { name: 'work-items.json file', exact: true }).waitFor();
  assert.deepEqual(JSON.parse(await contents.textContent()).workItems, []);
  const finding = fixture.run.findings[0];
  project.workItems.push({ id: 'WI-1', title: finding.title, priority: 'High', status: 'done', findingId: finding.id, finding }); project.revision++;
  fixture.state.snapshot.assessmentRevision++;
  await page.reload();
  await page.getByRole('article', { name: 'work-items.json file', exact: true }).waitFor();
  const work = JSON.parse(await contents.textContent());
  assert.equal(work.workItems[0].status, 'done'); assert.deepEqual(work.workItems[0].finding, finding);
  await panel.getByRole('region', { name: 'Projects', exact: true }).getByRole('button').filter({ has: page.getByText('Service app', { exact: true }) }).dblclick();
  await page.screenshot({ path: outputPath(`${label}-saved-project-context.png`) });
  assert.equal(fixture.stats.commands.filter(command => command.kind.startsWith('canvas.') && command.canvas?.kind === 'project-file').length, 0);
  await panel.getByRole('button', { name: 'All projects', exact: true }).click();
  assert.equal(current(page).target.projectId, project.id);
  fixture.state.snapshot.assessment.projects = []; fixture.state.snapshot.assessmentRevision++;
  await page.reload();
  await page.getByText('This file is unavailable in the selected project or worktree.', { exact: true }).first().waitFor();
  assert.equal(await contents.count(), 0, 'Deleted project context does not survive as a stale canvas copy');
  out.checks.push('Day-zero creation, project double-click from Home, saved context download, updated work items, reload and deleted-record isolation');
  await context.close();
  assert.deepEqual(out.errors, []);
} finally {
  writeFileSync(outputPath(`${label}-project-explorer.json`), JSON.stringify(out, null, 2));
  await browser.close(); cleanups.forEach(cleanup => cleanup()); modules.cleanup();
}
